import fs from 'node:fs';
import path from 'node:path';

const manifest = path.resolve('android/app/src/main/AndroidManifest.xml');
if (!fs.existsSync(manifest)) throw new Error('AndroidManifest.xml was not generated by Capacitor.');

let xml = fs.readFileSync(manifest, 'utf8');
if (xml.includes('android:scheme="com.digo.evolution"')) {
  console.log('Phantom callback URL scheme already configured.');
  process.exit(0);
}

const activityStart = xml.indexOf('<activity');
if (activityStart < 0) throw new Error('Main Android activity was not found.');
const activityEnd = xml.indexOf('</activity>', activityStart);
if (activityEnd < 0) throw new Error('Main Android activity closing tag was not found.');

const intentFilter = `
            <intent-filter>
                <action android:name="android.intent.action.VIEW" />
                <category android:name="android.intent.category.DEFAULT" />
                <category android:name="android.intent.category.BROWSABLE" />
                <data android:scheme="com.digo.evolution" android:host="phantom-callback" />
            </intent-filter>
`;

xml = xml.slice(0, activityEnd) + intentFilter + xml.slice(activityEnd);
fs.writeFileSync(manifest, xml);
console.log('Configured com.digo.evolution://phantom-callback for Phantom wallet redirects.');

const activityJava = path.resolve('android/app/src/main/java/com/digo/evolution/MainActivity.java');
fs.mkdirSync(path.dirname(activityJava), { recursive: true });
fs.writeFileSync(activityJava, `package com.digo.evolution;

import android.os.Bundle;
import android.view.View;
import com.getcapacitor.BridgeActivity;

public class MainActivity extends BridgeActivity {
    private void enterImmersiveMode() {
        getWindow().getDecorView().setSystemUiVisibility(
            View.SYSTEM_UI_FLAG_IMMERSIVE_STICKY
            | View.SYSTEM_UI_FLAG_FULLSCREEN
            | View.SYSTEM_UI_FLAG_HIDE_NAVIGATION
            | View.SYSTEM_UI_FLAG_LAYOUT_STABLE
            | View.SYSTEM_UI_FLAG_LAYOUT_FULLSCREEN
            | View.SYSTEM_UI_FLAG_LAYOUT_HIDE_NAVIGATION
        );
    }

    @Override
    public void onCreate(Bundle savedInstanceState) {
        super.onCreate(savedInstanceState);
        enterImmersiveMode();
    }

    @Override
    public void onWindowFocusChanged(boolean hasFocus) {
        super.onWindowFocusChanged(hasFocus);
        if (hasFocus) enterImmersiveMode();
    }
}
`);
console.log('Configured Android immersive full-screen mode (status and navigation bars hidden).');
